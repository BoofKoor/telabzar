"""شمارندهٔ پنجره‌دارِ Redis — تنها پیاده‌سازیِ «INCR و بعد EXPIRE».

`INCR` و `EXPIRE` دو فرمانِ جدا هستند. فرمِ رایجِ `if n == 1: expire(...)` فقط
روی اولین فراخوان TTL می‌گذارد، پس اگر پروسه دقیقاً بینِ این دو بمیرد (OOM، kill،
`telabzar update`) کلید **بدونِ انقضا** می‌ماند و شمارنده تا ابد بالا می‌رود. برای
یک سقفِ نرخ این یعنی قفلِ دائمی که خودش ترمیم نمی‌شود: `rate:<uid>`ِ ربات بعد از
آن کاربر را برای همیشه «زیادی سریع» می‌خواند، و فقط پاک‌کردنِ دستیِ کلید بازش
می‌کند (همان شکستِ `dl:active` در §۷).

این‌جا `expire` وقتی TTL گم باشد هم دوباره زده می‌شود، پس درخواستِ بعدی ترمیمش
می‌کند. عمداً بی‌وابستگی است (مثلِ `dl_active.py`): هم ربات می‌خواندش هم پنل، و
`routers/` نمی‌تواند `admin_web` را import کند.
"""
from __future__ import annotations


async def incr_window(redis, key: str, ttl: int, amount: int = 1) -> int:
    """`key` را `amount` واحد بالا می‌برد و مطمئن می‌شود TTL دارد؛ مقدارِ تازه را برمی‌گرداند.

    `ttl < 0` یعنی بی‌انقضا (`-1`) — کلید همین حالا با `INCRBY` ساخته شده پس
    `-2` (نبود) این‌جا رخ نمی‌دهد. روی اولین نوشتن (`n == amount`) چکِ TTL لازم
    نیست، پس مسیرِ عادی همان دو فرمانِ قبلی است و فقط فراخوان‌های بعدی یک `TTL`
    ارزان اضافه می‌کنند.
    """
    n = int(await redis.incrby(key, amount))
    if n == amount or await redis.ttl(key) < 0:
        await redis.expire(key, ttl)
    return n
