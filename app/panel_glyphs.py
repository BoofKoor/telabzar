"""شبکهٔ نقطه‌ایِ عددِ کانونیِ پنل (LCD/dot-matrix).

**چرا اصلاً وجود دارد.** اندازه‌گیریِ مقایسه‌ای با ماکتِ مرجع نشان داد
تفاوتِ اصلی رنگ یا مقیاسِ تایپ نیست (سبزِ ما بیشتر و نسبتِ تایپ ما بزرگ‌تر
بود) بلکه **تراکم** است و اینکه عددِ کانونی آن‌جا یک *فرمِ رسم‌شده* است نه یک
فونت‌سایزِ بزرگ. یک عدد به‌شکلِ شبکهٔ نقطه‌ای هم‌زمان هر دو را می‌دهد: کانونی
می‌شود و ~۲۰۰ سلولِ بافت به صفحه اضافه می‌کند.

**چرا ماژولِ جدا و نه داخلِ قالب.** ماتریسِ حروف داده است نه نشانه‌گذاری، و
`admin_web` در محیطِ تست import‌شدنی نیست — پس هرچه بخواهد قابلِ سنجش بماند
باید بیرونش زندگی کند، مثلِ `panel_i18n`/`langpack`/`dl_active`.

فونت ۵×۷ است: کوچک‌ترین شبکه‌ای که ارقام در آن بدونِ ابهام خوانده می‌شوند
(۳×۵ رقمِ ۶ و ۸ را شبیه می‌کند).
"""
from __future__ import annotations

W, H = 5, 7

#: هر رشته یک ردیفِ ۵بیتی است. فقط نویسه‌هایی که واقعاً در عددهای پنل ظاهر
#: می‌شوند: ارقام، جداکنندهٔ هزارگان، ممیز، درصد و خطِ تیره برای «نامعلوم».
_FONT: dict[str, tuple[str, ...]] = {
    "0": ("01110", "10001", "10011", "10101", "11001", "10001", "01110"),
    "1": ("00100", "01100", "00100", "00100", "00100", "00100", "01110"),
    "2": ("01110", "10001", "00001", "00010", "00100", "01000", "11111"),
    "3": ("11111", "00010", "00100", "00010", "00001", "10001", "01110"),
    "4": ("00010", "00110", "01010", "10010", "11111", "00010", "00010"),
    "5": ("11111", "10000", "11110", "00001", "00001", "10001", "01110"),
    "6": ("00110", "01000", "10000", "11110", "10001", "10001", "01110"),
    "7": ("11111", "00001", "00010", "00100", "01000", "01000", "01000"),
    "8": ("01110", "10001", "10001", "01110", "10001", "10001", "01110"),
    "9": ("01110", "10001", "10001", "01111", "00001", "00010", "01100"),
    "%": ("11001", "11010", "00010", "00100", "01000", "01011", "10011"),
    ".": ("00000", "00000", "00000", "00000", "00000", "01100", "01100"),
    ",": ("00000", "00000", "00000", "00000", "01100", "00100", "01000"),
    "-": ("00000", "00000", "00000", "11111", "00000", "00000", "00000"),
    "—": ("00000", "00000", "00000", "11111", "00000", "00000", "00000"),
    " ": ("00000",) * H,
}
_FALLBACK = ("11111", "10001", "10001", "10001", "10001", "10001", "11111")

#: فاصلهٔ بینِ دو نویسه، بر حسبِ ستون.
GAP = 1


def lcd(text: str, limit: int = 9) -> tuple[int, list[int]]:
    """`(تعدادِ ستون, سلول‌ها به ترتیبِ سطری)` — هر سلول ۰ یا ۱.

    خروجی **صاف** است نه تودرتو، چون قالب دقیقاً همان را می‌خواهد: یک
    `grid` با `--cols` ستون و یک `<i>` به‌ازای هر سلول. سلولِ خاموش هم
    رندر می‌شود — همان چیزی است که شبکه را به بافت تبدیل می‌کند.

    `limit` جلوی عددی را می‌گیرد که از عرضِ اسلب بیرون بزند؛ بریدن از
    **چپ** انجام نمی‌شود چون رقمِ پرارزش را می‌خورد — به‌جایش نویسه‌های
    اضافه کنار گذاشته می‌شوند و ارقامِ اول می‌مانند.
    """
    chars = [c for c in str(text) if c in _FONT or c.isprintable()][:limit]
    if not chars:
        chars = ["—"]
    cols = len(chars) * W + (len(chars) - 1) * GAP
    cells: list[int] = []
    for row in range(H):
        for i, ch in enumerate(chars):
            if i:
                cells.extend([0] * GAP)
            bits = _FONT.get(ch, _FALLBACK)[row]
            cells.extend(1 if b == "1" else 0 for b in bits)
    return cols, cells
