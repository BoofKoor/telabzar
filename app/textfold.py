"""شکلِ جست‌وجوپذیرِ متن — **یک** قاعده برای پنل و ربات.

حروفِ کوچک، «ي/ى/ك»ِ عربی → «ی/ک»ِ فارسی، و بی‌نیم‌فاصله و نشانهٔ جهت — وگرنه
«میشود» «می‌شود» را پیدا نمی‌کرد و نامی که با کیبوردِ عربی تایپ شده هرگز جور
نمی‌شد. همان قاعده‌ای است که `fold`ِ `app/static/js/panel.js` دارد؛ تستِ
`tests/panel/test_texts_inplace.py` regexِ خودِ JS را در پایتون اجرا و با این
مقایسه می‌کند.

چرا ماژولِ جدا و نه همان `admin_web`: جست‌وجوی تاریخچهٔ ربات (`app/history.py`)
هم همین را لازم دارد، و ربات نمی‌تواند `admin_web` را import کند (ایمیجش
jinja2/cryptography ندارد) — کپیِ دومِ دست‌نویس همان واگرایی است که §۷ بارها
ثبتش کرده. نویسه‌های نامرئی و هم‌شکل عمداً با `\\uXXXX` نوشته شده‌اند، نه خام:
در بازبینی دیده نمی‌شوند و ویرایشگر می‌تواند بی‌صدا عوضشان کند.
"""
from __future__ import annotations

_FOLD = str.maketrans({"\u064a": "\u06cc", "\u0649": "\u06cc", "\u0643": "\u06a9",
                       "\u200c": None, "\u200d": None, "\u200e": None, "\u200f": None})


def fold(s: str) -> str:
    return s.lower().translate(_FOLD)
